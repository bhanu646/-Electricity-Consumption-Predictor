"""
Prediction History Page: Inspect logged user predictions stored in SQLite.
Allows filtering, downloading logs as CSV, and clearing history.
"""

import streamlit as st
import pandas as pd
from src.database import get_all_predictions, clear_predictions

def render_history_page():
    """Renders the Prediction History page."""
    st.title("📜 Prediction History & Audit Log")
    st.markdown("""
        Every prediction generated by users is automatically timestamped and persisted
        into a lightweight local SQLite database (`data/predictions.db`).
    """)

    # Fetch records
    df_history = get_all_predictions(limit=200)

    if df_history.empty:
        st.info("No prediction logs recorded yet. Visit the **'Predict Consumption'** page to generate predictions!")
        return

    # Metrics Summary
    total_logged = len(df_history)
    avg_predicted = round(df_history['predicted_consumption'].mean(), 2)
    max_predicted = round(df_history['predicted_consumption'].max(), 2)
    min_predicted = round(df_history['predicted_consumption'].min(), 2)

    col1, col2, col3, col4 = st.columns(4)
    with col1:
        st.metric("Total Predictions", f"{total_logged}")
    with col2:
        st.metric("Avg Predicted (kWh)", f"{avg_predicted}")
    with col3:
        st.metric("Max Predicted (kWh)", f"{max_predicted}")
    with col4:
        st.metric("Min Predicted (kWh)", f"{min_predicted}")

    st.markdown("---")

    # Filter controls
    f_col1, f_col2 = st.columns([2, 1])
    with f_col1:
        model_options = ["All Models"] + list(df_history['model_used'].unique())
        selected_model = st.selectbox("Filter by Model:", model_options)
    with f_col2:
        max_rows = st.number_input("Max records to display:", min_value=5, max_value=200, value=50, step=10)

    filtered_df = df_history.copy()
    if selected_model != "All Models":
        filtered_df = filtered_df[filtered_df['model_used'] == selected_model]

    # Present formatted dataframe
    col_rename = {
        'id': 'ID',
        'timestamp': 'Timestamp',
        'temperature': 'Temp (°C)',
        'humidity': 'Humidity (%)',
        'number_of_people': 'Occupants',
        'previous_day_consumption': 'Prev Day (kWh)',
        'day_of_week': 'Weekday',
        'is_weekend': 'Weekend?',
        'appliance_usage': 'Appliances (hrs)',
        'predicted_consumption': 'Predicted (kWh)',
        'model_used': 'Model'
    }
    
    display_df = filtered_df.rename(columns=col_rename).head(int(max_rows))
    st.dataframe(display_df, use_container_width=True, hide_index=True)

    # Action buttons: Download & Clear
    st.markdown("---")
    b_col1, b_col2, _ = st.columns([2, 2, 4])
    
    with b_col1:
        csv_data = filtered_df.to_csv(index=False).encode('utf-8')
        st.download_button(
            label="📥 Export History as CSV",
            data=csv_data,
            file_name="prediction_history_export.csv",
            mime="text/csv",
            use_container_width=True
        )

    with b_col2:
        if st.button("🗑️ Clear History Log", type="secondary", use_container_width=True):
            clear_predictions()
            st.warning("History cleared! Refreshing...")
            st.rerun()
